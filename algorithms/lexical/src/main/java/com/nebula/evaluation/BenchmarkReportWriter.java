package com.nebula.evaluation;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Locale;

/** Writes a durable Markdown artifact containing metrics, deltas, and errors. */
public final class BenchmarkReportWriter {
    public void write(Path target, int corpusDocuments, int queryCount,
                      RankingComparisonReport comparison, List<QueryErrorAnalysis> errors) throws IOException {
        if (target.getParent() != null) Files.createDirectories(target.getParent());
        StringBuilder report = new StringBuilder();
        report.append("# NEBULA Retrieval Benchmark Report\n\n");
        report.append("> Generated by the reproducible evaluation runner. This artifact is an engineering regression report, not a publication claim.\n\n");
        report.append("- Corpus documents: ").append(corpusDocuments).append('\n');
        report.append("- Labelled queries: ").append(queryCount).append('\n');
        report.append("- Cutoff: @").append(comparison.get("bm25").getCutoff()).append("\n\n");
        report.append("## Ranking comparison\n\n");
        report.append("| Variant | Precision | Recall | MRR | NDCG | Delta NDCG vs BM25 |\n");
        report.append("| --- | ---: | ---: | ---: | ---: | ---: |\n");
        for (String variant : comparison.getVariants()) {
            EvaluationReport metrics = comparison.get(variant);
            double ndcgDelta = "bm25".equals(variant) ? 0.0 : comparison.ndcgDelta(variant, "bm25");
            report.append('|').append(variant).append('|')
                    .append(number(metrics.getMeanPrecisionAtK())).append('|')
                    .append(number(metrics.getMeanRecallAtK())).append('|')
                    .append(number(metrics.getMeanReciprocalRank())).append('|')
                    .append(number(metrics.getMeanNdcgAtK())).append('|')
                    .append(number(ndcgDelta)).append("|\n");
        }
        report.append("\n## Error analysis\n\n");
        for (QueryErrorAnalysis error : errors) {
            report.append("### ").append(error.getVariant()).append(" / ").append(error.getQueryId()).append("\n\n");
            report.append("- Missed relevant sources: ").append(list(error.getMissedRelevantSources())).append('\n');
            report.append("- Unexpected sources: ").append(list(error.getUnexpectedSources())).append('\n');
            report.append("- Returned ranks: ").append(error.getReturnedRanks()).append("\n\n");
        }
        report.append("## Interpretation guidance\n\n");
        report.append("Trust-aware variants should only be preferred when improvements are supported by the metrics and error analysis. Investigate cases where authority or freshness promotes an irrelevant source.\n");
        Files.write(target, report.toString().getBytes(StandardCharsets.UTF_8));
    }

    private static String number(double value) { return String.format(Locale.ROOT, "%.4f", value); }

    private static String list(List<String> values) {
        return values.isEmpty() ? "none" : String.join(", ", values);
    }
}
